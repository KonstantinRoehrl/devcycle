import { test } from "node:test";
import assert from "node:assert/strict";
import { GENERATED_MARKER, HEAD_LINES, exclusionCategory, isExcluded, linguistAttributes, matchesAttribute } from "../../scripts/generated-paths.mjs";
import { isExcluded as reviewDepthIsExcluded } from "../../scripts/review-depth.mjs";

test("review-depth re-exports the one isExcluded", () => {
  assert.equal(reviewDepthIsExcluded, isExcluded);
  assert.equal(isExcluded("web/yarn.lock"), true);
  assert.equal(isExcluded("src/index.js"), false);
});

test("exclusionCategory names lockfiles, vendored, generated and fixture paths", () => {
  const cases = {
    "package-lock.json": "lockfile", "web/go.sum": "lockfile",
    "vendor/lib.rb": "vendored", "node_modules/x/i.js": "vendored",
    "dist/index.js": "generated", "pkg/build/out.js": "generated", "app.min.js": "generated", "api/schema.generated.ts": "generated",
    "tests/fixtures/a.json": "test-fixture", "src/__fixtures__/b.ts": "test-fixture", "go/testdata/c.go": "test-fixture",
    "src/index.js": null, "docs/dist.md": null, "src/fixture.ts": null,
  };
  for (const [path, want] of Object.entries(cases)) assert.equal(exclusionCategory(path), want, path);
});

test("a header marker in the file's first lines makes it generated", () => {
  assert.equal(HEAD_LINES, 5);
  for (const head of ["// @generated by protoc", "// Code generated by mockgen. DO NOT EDIT.", "<!-- <auto-generated> -->", "# DO NOT EDIT"]) {
    assert.match(head, GENERATED_MARKER);
    assert.equal(exclusionCategory("src/client.ts", { head }), "generated", head);
  }
  assert.equal(exclusionCategory("src/client.ts", { head: "// edit freely\nexport const x = 1;" }), null);
});

test(".gitattributes linguist entries mark generated and vendored paths", () => {
  const attributes = linguistAttributes([
    "# comment linguist-generated",
    "api/** linguist-generated",
    "third_party/ linguist-vendored=true",
    "*.pb.go linguist-generated=true linguist-vendored",
    "docs/** -linguist-generated",
    "keep.js linguist-generated=false",
  ].join("\n"));
  assert.deepEqual(attributes, [
    { pattern: "api/**", attr: "generated" },
    { pattern: "third_party/", attr: "vendored" },
    { pattern: "*.pb.go", attr: "generated" },
    { pattern: "*.pb.go", attr: "vendored" },
  ]);
  assert.equal(exclusionCategory("api/v1/client.ts", { attributes }), "generated");
  assert.equal(exclusionCategory("third_party/x/y.c", { attributes }), "vendored");
  assert.equal(exclusionCategory("svc/deep/msg.pb.go", { attributes }), "vendored", "vendored is checked before generated");
  assert.equal(exclusionCategory("docs/guide.md", { attributes }), null);
});

test("matchesAttribute follows gitattributes globbing", () => {
  assert.equal(matchesAttribute("*.pb.go", "a/b/x.pb.go"), true);
  assert.equal(matchesAttribute("api/*.ts", "api/x.ts"), true);
  assert.equal(matchesAttribute("api/*.ts", "api/v1/x.ts"), false);
  assert.equal(matchesAttribute("api/**", "api/v1/x.ts"), true);
  assert.equal(matchesAttribute("**/gen/*.js", "a/b/gen/x.js"), true);
  assert.equal(matchesAttribute("third_party/", "third_party/x/y.c"), true);
  assert.equal(matchesAttribute("third_party/", "src/third_party.c"), false);
  assert.equal(matchesAttribute("x?.js", "xa.js"), true);
});
